for (const [text, kind, expected] of cases) {
  const parsed = Payroll.parsePortalPaste("\ufeff" + text);
  assert.ok(parsed, `${kind} 인식`);
  assert.equal(parsed.kind, kind, `${kind} 종류`);
  assert.deepEqual(parsed.rows.map((r) => [r.name, r.values]), expected, `${kind} 행`);
  assert.deepEqual(parsed.invalid, [], `${kind} 잘못된 금액 없음`);
}

